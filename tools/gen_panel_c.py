#!/usr/bin/env python3
"""gen_panel_c.py - turn the vendor p255_inx DSI command arrays into a C header.

Vendor command buffer format (verified against the stock DTS):
    [dtype][last][vc][ack][wait][len_hi][len_lo][payload ...]
dtype 0x39 = generic long write, 0x15 = dcs short write with 1 param,
0x05 = dcs short write no param, wait is in ms.
"""
import re
import sys

DTS = r'D:\TB331FC_GSI_Kit\device_specific_backup\tb331fc_stock.dts'
NODE = 'p255_inx'
OUT = sys.argv[1] if len(sys.argv) > 1 else r'D:\TB331FCLinux\build\p255_inx_init.h'

t = open(DTS, encoding='utf-8', errors='replace').read()
m = re.search(r'^[ \t]*([A-Za-z0-9_,.\-]*' + re.escape(NODE) + r'[A-Za-z0-9_,.\-]*)[ \t]*\{', t, re.M)
if not m:
    sys.exit('panel node not found')
j = t.index('{', m.start())
depth = 0
k = j
while k < len(t):
    if t[k] == '{':
        depth += 1
    elif t[k] == '}':
        depth -= 1
        if depth == 0:
            break
    k += 1
body = t[j + 1:k]


def get_array(prop):
    mm = re.search(r'^[ \t]*' + re.escape(prop) + r'\s*=\s*\[([^\]]*)\];', body, re.M | re.S)
    if not mm:
        return None
    return [int(x, 16) for x in mm.group(1).split() if re.fullmatch(r'[0-9a-fA-F]{2}', x)]


def emit(name, data):
    if not data:
        return f'/* {name}: not present */\n'
    lines = [f'static const u8 {name}[] = {{']
    for i in range(0, len(data), 12):
        chunk = ', '.join(f'0x{b:02x}' for b in data[i:i + 12])
        lines.append(f'\t{chunk},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


on = get_array('qcom,mdss-dsi-on-command')
off = get_array('qcom,mdss-dsi-off-command')

out = []
out.append('/* Generated by tools/gen_panel_c.py - do not edit. */')
out.append('/* Source: tb331fc_stock.dts, node qcom,mdss_dsi_panel_p255_inx_fhd_video */')
out.append('')
out.append(emit('p255_inx_on_seq', on))
if off:
    out.append(emit('p255_inx_off_seq', off))

open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))

# report stats
def packets(d):
    i = 0
    n = 0
    waits = 0
    while i + 7 <= len(d):
        dtype = d[i]
        wait = d[i + 4]
        ln = (d[i + 5] << 8) | d[i + 6]
        if dtype not in (0x05, 0x15, 0x39):
            return n, waits, f'unexpected dtype 0x{dtype:02x} at {i}'
        if i + 7 + ln > len(d):
            return n, waits, f'truncated at {i}'
        if wait:
            waits += 1
        i += 7 + ln
        n += 1
    return n, waits, 'ok' if i == len(d) else f'trailing {len(d)-i} bytes'

print(f'on  array: {len(on)} bytes  -> {packets(on)}')
if off:
    print(f'off array: {len(off)} bytes -> {packets(off)}')
print(f'wrote {OUT}')
